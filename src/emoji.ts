const NAMES = new Map(EMOJI.map(([e, name]) => [e, name]));

/** What the picker shows before anything is typed, in its order. */
export const FREQUENT: readonly string[] = EMOJI.slice(0, 12).map(([e]) => e);

/** The name a key is read out as: its own where it is listed, else the
 *  key itself. */
export function emojiName(emoji: string): string {
  return NAMES.get(emoji) ?? emoji;
}

/** The emoji whose name or words start a word with each of `query`'s,
 *  in the list's order; every one for an empty query. */
export function searchEmoji(query: string): string[] {
  const asked = query.toLowerCase().split(/\s+/).filter(Boolean);
  return EMOJI.filter(([, name, words]) => {
    const said = `${name} ${words}`.toLowerCase().split(/[\s-]+/);
    return asked.every((q) => said.some((w) => w.startsWith(q)));
  }).map(([e]) => e);
}
